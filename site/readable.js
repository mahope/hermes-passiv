/* readable.js — find the article inside a fetched HTML page.
 *
 * It lived inline in `/url-to-markdown` and `/url-til-markdown`, byte for byte
 * the same fifteen lines in both, and this file's front-door check needed it a
 * third time. That is the same failure shape `net.js` was written to stop: the
 * rule is correct in every copy, so nothing looks wrong until the copies drift
 * and only one of them is still right.
 *
 * Pure string work, no DOM and no dependencies, so it runs the same in a
 * browser as in Node. The function itself is moved verbatim — the point is the
 * move, not a rewrite. `htmlToMarkdown` in `clean-copy-core.js` does the
 * actual conversion; this only decides *which* HTML to hand it.
 *
 * `clean-copy-core.js` would be the natural home, but that file is generated by
 * `tools/sync_core.js` from `tools/clean_copy_core.js`, which mirrors the
 * `mahope/clean-copy` repo and is shared by the extension, the CLI and the
 * Obsidian and VS Code plugins. A front-door heuristic does not belong in code
 * that ships to seven surfaces and has a parity test, so it lives here and the
 * core is left alone.
 */
(function (global) {
  'use strict';

  /* Strip what never belongs in a converted article, then keep the largest
   * <article>/<main>/<div> block that holds more than 200 characters of text.
   * Falling back to the whole stripped document is deliberate: a short page is
   * better converted whole than reported as empty.
   */
  function extractReadable(html) {
    var doc = html
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/<(script|style|noscript)\b[^>]*>[\s\S]*?<\/\1>/gi, '')
      .replace(/<(script|style|noscript|link|meta)\b[^>]*\/?>/gi, '');
    doc = doc.replace(/<(nav|footer|header|aside|form|svg|iframe)\b[^>]*>[\s\S]*?<\/\1>/gi, '');
    var candidates = [];
    var re = /<(article|main|div)\b[^>]*>/gi;
    var m;
    while ((m = re.exec(doc)) !== null) candidates.push(m.index);
    var best = null, bestLen = 0;
    for (var i = 0; i < candidates.length; i++) {
      var start = candidates[i];
      var openTagEnd = doc.indexOf('>', start);
      var tag = doc.slice(start + 1, openTagEnd).split(/\s/)[0];
      var closeIdx = doc.lastIndexOf('</' + tag + '>');
      if (closeIdx <= openTagEnd) continue;
      var inner = doc.slice(openTagEnd + 1, closeIdx);
      var len = inner.replace(/<[^>]*>/g, '').length;
      if (len > bestLen && len > 200) { best = inner; bestLen = len; }
    }
    return best || doc;
  }

  global.CleanCopyReadable = { extract: extractReadable };
})(typeof self !== 'undefined' ? self : this);
